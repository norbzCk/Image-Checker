<?php
declare(strict_types=1);

/** Orchestrates: store upload -> record -> ask inference service -> save result. */
final class AnalysisService
{
    public const RATE_LIMIT_COUNT   = 10;
    public const RATE_LIMIT_SECONDS = 600;

    public function __construct(
        private AnalysisRepository $repo,
        private InferenceClient $inference,
        private string $uploadDir,
    ) {
    }

    /** @param array<string,mixed> $validated output of UploadValidator::validate() */
    public function submit(array $validated, string $ownerHash, string $clientHash): int
    {
        if ($this->repo->countRecentByClient($clientHash, self::RATE_LIMIT_SECONDS) >= self::RATE_LIMIT_COUNT) {
            throw new UserError('Too many uploads. Please wait a few minutes and try again.');
        }

        $storedName  = bin2hex(random_bytes(16)) . '.' . $validated['ext'];
        $destination = $this->pathFor($storedName);

        if (!move_uploaded_file($validated['tmp'], $destination)) {
            throw new RuntimeException('Could not save the uploaded file.');
        }
        chmod($destination, 0640);

        try {
            $id = $this->repo->create($ownerHash, $clientHash, $storedName, $validated);
        } catch (Throwable $e) {
            @unlink($destination);
            throw $e;
        }

        $this->run($id, $ownerHash);
        return $id;
    }

    /** Runs (or re-runs) inference for a stored image and records the outcome. */
    public function run(int $id, string $ownerHash): void
    {
        $row = $this->repo->find($id, $ownerHash);
        if ($row === null) {
            throw new UserError('Image not found.');
        }

        try {
            $result = $this->inference->analyze($this->pathFor((string) $row['stored_filename']), (string) $row['mime_type']);
            $this->repo->markDone($id, $result);
        } catch (InferenceRejected $e) {
            $this->repo->markFailed($id, $e->getMessage());
        } catch (Throwable $e) {
            error_log('ImageCheck inference error: ' . $e->getMessage());
            $this->repo->markFailed($id, 'The analysis service is unavailable right now. Try again in a moment.');
        }
    }

    public function delete(int $id, string $ownerHash): void
    {
        $stored = $this->repo->delete($id, $ownerHash);
        if ($stored !== null) {
            @unlink($this->pathFor($stored));
        }
    }

    public function pathFor(string $storedName): string
    {
        // stored names are generated by us; this guards against any tampered DB value.
        if (!preg_match('/^[a-f0-9]{32}\.(jpg|png|webp|gif)$/', $storedName)) {
            throw new RuntimeException('Invalid stored filename.');
        }
        return rtrim($this->uploadDir, '/') . '/' . $storedName;
    }
}
